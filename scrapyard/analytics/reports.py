from typing import List, Dict, Optional, Any, Callable, TypeVar, Generic
from datetime import datetime, timezone
import json
import os
import tempfile

from sqlalchemy import String, Boolean, DateTime, JSON, Integer
from sqlalchemy.orm import Mapped, mapped_column, Session
from sqlalchemy.exc import NoResultFound
from fastapi import HTTPException

from scrapyard.database.base_model import IntPKModel

STATUS = "core"

T = TypeVar('T')


class Page(Generic[T]):
    def __init__(self, items: List[T], total: int):
        self.items = items
        self.total = total


class Report(IntPKModel):
    """Persisted report definition (ORM model - the previous pydantic
    stand-in could not be stored or queried)."""
    __tablename__ = "analytics_reports"

    name: Mapped[str] = mapped_column(String(255), nullable=False)
    config: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    owner_id: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False,
        default=lambda: datetime.now(timezone.utc))


class ReportNotFoundError(HTTPException):
    def __init__(self):
        super().__init__(status_code=404, detail="Report not found")


_REPORT_HOOKS: Dict[str, Callable] = {}


def add_report_hook(name: str, callback: Callable) -> None:
    """Register a callback fired with (report, format) after each generation."""
    if not callable(callback):
        raise ValueError("callback must be callable")
    _REPORT_HOOKS[name] = callback


def remove_report_hook(name: str) -> None:
    _REPORT_HOOKS.pop(name, None)


def create_report(db: Session, name: str, config: dict, user_id: int) -> Report:
    if not name:
        raise ValueError("Report name is required")
    report = Report(name=name, config=dict(config or {}), owner_id=user_id)
    db.add(report)
    db.commit()
    db.refresh(report)
    return report


def get_report(db: Session, report_id: int) -> Report:
    try:
        return db.query(Report).filter(Report.id == report_id).one()
    except NoResultFound:
        raise ReportNotFoundError()


def list_reports(db: Session, filters: Optional[Dict[str, Any]] = None, page: int = 1, per_page: int = 20) -> Page[Report]:
    query = db.query(Report)
    if filters:
        for key, value in filters.items():
            if not hasattr(Report, key):
                raise ValueError(f"Unknown report filter: {key}")
            query = query.filter(getattr(Report, key) == value)
    total = query.count()
    reports = query.offset((page - 1) * per_page).limit(per_page).all()
    return Page(items=reports, total=total)


def update_report(db: Session, report_id: int, config: dict) -> Report:
    report = get_report(db, report_id)
    report.config = dict(config or {})
    db.commit()
    db.refresh(report)
    return report


def archive_report(db: Session, report_id: int) -> None:
    report = get_report(db, report_id)
    report.archived = True
    db.commit()


def _csv_escape(value: Any) -> str:
    text = "" if value is None else str(value)
    if any(ch in text for ch in (',', '"', '\n', '\r')):
        return '"' + text.replace('"', '""') + '"'
    return text


def generate_report(db: Session, report_id: int, format: str = "csv") -> bytes:
    """Render the report definition to bytes (csv or json)."""
    report = get_report(db, report_id)
    if format == "json":
        payload = json.dumps(serialize_report(report), indent=2, default=str).encode("utf-8")
    elif format == "csv":
        lines = ["key,value"]
        lines.append(f"name,{_csv_escape(report.name)}")
        lines.append(f"owner_id,{report.owner_id}")
        for key, value in sorted((report.config or {}).items()):
            lines.append(f"{_csv_escape(key)},{_csv_escape(value)}")
        payload = ("\n".join(lines) + "\n").encode("utf-8")
    else:
        raise ValueError(f"Unsupported report format: {format}")

    for hook in list(_REPORT_HOOKS.values()):
        try:
            hook(report, format)
        except Exception:
            import logging
            logging.getLogger(__name__).warning("report hook failed", exc_info=True)
    return payload


def export_report(db: Session, report_id: int, format: str = "csv",
                  output_dir: Optional[str] = None) -> str:
    """Generate the report and write it to disk; returns the real file path.

    The filename is derived from the report id, never from the user-supplied
    name, so report names cannot traverse paths.
    """
    data = generate_report(db, report_id, format)
    directory = output_dir or tempfile.gettempdir()
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, f"report_{report_id}.{format}")
    with open(path, "wb") as fh:
        fh.write(data)
    return path


def serialize_report(report: Report) -> dict:
    return {
        "id": report.id,
        "name": report.name,
        "config": report.config,
        "owner_id": report.owner_id,
        "archived": report.archived,
    }


def bulk_generate_reports(db: Session, report_ids: List[int], format: str = "csv") -> List[bytes]:
    return [generate_report(db, report_id, format) for report_id in report_ids]


def apply_report_policy(report: Report, user: Any) -> bool:
    """Owner-only access; archived reports are closed to everyone."""
    if report.archived:
        return False
    user_id = getattr(user, "id", user)
    return user_id == report.owner_id


