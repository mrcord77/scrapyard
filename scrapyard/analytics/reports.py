def summary_report(db):
    from scrapyard.analytics.usage_metrics import active_users, events_by_name
    return {"active_users": active_users(db), "events_by_name": events_by_name(db)}


def _selftest() -> None:
    from sqlalchemy import create_engine
    # Import before create_all so the analytics_events table is registered.
    from scrapyard.analytics.event_tracking import track_event

    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmpdir:
        engine = create_engine(f"sqlite:///{os.path.join(tmpdir, 'test.db')}")
        IntPKModel.metadata.create_all(engine)
        try:
            with Session(engine) as db:
                rep = create_report(db, 'Monthly, "Sales"', {"metric": "revenue", "window": "30d"}, user_id=7)
                assert rep.id is not None and rep.config["metric"] == "revenue"

                fetched = get_report(db, rep.id)
                assert fetched.name == 'Monthly, "Sales"'
                try:
                    get_report(db, 999999)
                    assert False
                except HTTPException as e:
                    assert e.status_code == 404

                # listing + filters
                create_report(db, "Other", {}, user_id=8)
                page = list_reports(db, {"owner_id": 7})
                assert page.total == 1 and page.items[0].id == rep.id
                try:
                    list_reports(db, {"nope": 1})
                    assert False
                except ValueError:
                    pass

                # update
                update_report(db, rep.id, {"metric": "signups"})
                assert get_report(db, rep.id).config == {"metric": "signups"}

                # generation: real content, both formats, hook fires
                fired = []
                add_report_hook("audit", lambda r, f: fired.append((r.id, f)))
                try:
                    csv_bytes = generate_report(db, rep.id, "csv")
                    json_bytes = generate_report(db, rep.id, "json")
                finally:
                    remove_report_hook("audit")
                assert b"metric,signups" in csv_bytes
                assert b'"Monthly, ""Sales"""' in csv_bytes  # csv escaping
                assert json.loads(json_bytes)["config"] == {"metric": "signups"}
                assert fired == [(rep.id, "csv"), (rep.id, "json")]
                try:
                    generate_report(db, rep.id, "xlsx")
                    assert False
                except ValueError:
                    pass

                # export writes a real file derived from the id
                path = export_report(db, rep.id, "csv", output_dir=tmpdir)
                assert os.path.basename(path) == f"report_{rep.id}.csv"
                with open(path, "rb") as fh:
                    assert fh.read() == csv_bytes

                # bulk
                blobs = bulk_generate_reports(db, [rep.id], "json")
                assert len(blobs) == 1 and json.loads(blobs[0])["id"] == rep.id

                # policy: owner-only, archived closed
                class U:
                    def __init__(self, id):
                        self.id = id
                assert apply_report_policy(rep, U(7)) is True
                assert apply_report_policy(rep, U(8)) is False
                archive_report(db, rep.id)
                assert apply_report_policy(get_report(db, rep.id), U(7)) is False

                # summary_report over event data
                track_event(db, "login", user_id=1)
                db.commit()
                summary = summary_report(db)
                assert summary["active_users"] == 1
                assert summary["events_by_name"] == {"login": 1}
        finally:
            engine.dispose()


if __name__ == "__main__":
    _selftest()
    print("reports selftest OK")
